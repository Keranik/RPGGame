namespace RPGGame.Core.Characters;

/// <summary>
/// Unique identifiers for character classes.
/// </summary>
public static class CharacterClassId {
	// ???????????????????????????????????????????????????????????????
	// STARTER CLASSES (Unlocked from start)
	// ???????????????????????????????????????????????????????????????

	/// <summary>
	/// Warrior - balanced melee fighter with high durability.
	/// </summary>
	public const string Warrior = "warrior";

	// ???????????????????????????????????????????????????????????????
	// UNLOCKABLE CLASSES
	// ???????????????????????????????????????????????????????????????

	/// <summary>
	/// Rogue - agile fighter focused on critical hits and evasion.
	/// </summary>
	public const string Rogue = "rogue";

	/// <summary>
	/// Mage - spellcaster with powerful but limited abilities.
	/// </summary>
	public const string Mage = "mage";

	/// <summary>
	/// Ranger - hybrid class with ranged attacks and survival skills.
	/// </summary>
	public const string Ranger = "ranger";

	/// <summary>
	/// Cleric - support class with healing and defensive magic.
	/// </summary>
	public const string Cleric = "cleric";

	/// <summary>
	/// Berserker - high damage but low defense rage fighter.
	/// </summary>
	public const string Berserker = "berserker";

	/// <summary>
	/// Paladin - holy warrior with balanced offense and healing.
	/// </summary>
	public const string Paladin = "paladin";

	/// <summary>
	/// Necromancer - dark mage who sacrifices health for power.
	/// </summary>
	public const string Necromancer = "necromancer";

	/// <summary>
	/// Monk - unarmed fighter with ki abilities.
	/// </summary>
	public const string Monk = "monk";

	/// <summary>
	/// Bard - jack of all trades with inspiration abilities.
	/// </summary>
	public const string Bard = "bard";

	// ???????????????????????????????????????????????????????????????
	// SECRET CLASSES (Special unlock conditions)
	// ???????????????????????????????????????????????????????????????

	/// <summary>
	/// Ascended - special class unlocked after true ending.
	/// </summary>
	public const string Ascended = "ascended";

	/// <summary>
	/// Time Walker - unlocked after many rewinds.
	/// </summary>
	public const string TimeWalker = "time_walker";

	// ???????????????????????????????????????????????????????????????
	// HELPER METHODS
	// ???????????????????????????????????????????????????????????????

	/// <summary>
	/// All base class IDs.
	/// </summary>
	public static IReadOnlyList<string> AllClasses => [
		Warrior, Rogue, Mage, Ranger, Cleric,
		Berserker, Paladin, Necromancer, Monk, Bard,
		Ascended, TimeWalker
	];

	/// <summary>
	/// Classes available from the start.
	/// </summary>
	public static IReadOnlyList<string> StarterClasses => [Warrior];

	/// <summary>
	/// Standard unlockable classes.
	/// </summary>
	public static IReadOnlyList<string> UnlockableClasses => [
		Rogue, Mage, Ranger, Cleric, Berserker,
		Paladin, Necromancer, Monk, Bard
	];

	/// <summary>
	/// Secret classes with special unlock conditions.
	/// </summary>
	public static IReadOnlyList<string> SecretClasses => [
		Ascended, TimeWalker
	];

	/// <summary>
	/// Checks if a class ID is valid.
	/// </summary>
	public static bool IsValid(string classId) => AllClasses.Contains(classId);
}