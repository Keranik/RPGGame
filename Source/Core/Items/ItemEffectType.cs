/// <summary>
/// An effect applied when an item is used.
/// </summary>
public class ItemEffect {
	/// <summary>
	/// Type of effect.
	/// </summary>
	public ItemEffectType Type { get; set; } = ItemEffectType.None;

	/// <summary>
	/// Numeric value (amount to heal, damage, etc.).
	/// </summary>
	public float Value { get; set; }

	/// <summary>
	/// Duration in ticks/turns (for buffs, DoTs).
	/// </summary>
	public int Duration { get; set; }

	/// <summary>
	/// String parameter (condition name, buff ID, etc.).
	/// </summary>
	public string Parameter { get; set; } = "";

	/// <summary>
	/// Secondary value (for ranges, etc.).
	/// </summary>
	public float SecondaryValue { get; set; }

	/// <summary>
	/// Gets a display description for this effect.
	/// </summary>
	public string GetDescription() {
		return Type switch {
			ItemEffectType.Heal => $"Restores {Value} HP",
			ItemEffectType.HealOverTime => $"Restores {Value} HP over {Duration} turns",
			ItemEffectType.RestoreMana => $"Restores {Value} mana",
			ItemEffectType.ReduceFatigue => $"Reduces fatigue by {Value}",
			ItemEffectType.AddMorale => $"+{Value} morale",
			ItemEffectType.CureCondition => $"Cures {Parameter}",
			ItemEffectType.CureAllConditions => "Cures all conditions",
			ItemEffectType.ApplyBuff => $"Applies {Parameter} for {Duration} turns",
			ItemEffectType.TempStatBoost => $"+{Value} to stat for {Duration} turns",
			ItemEffectType.Damage => $"Deals {Value} damage",
			ItemEffectType.AddFood => $"+{Value} food",
			ItemEffectType.AddMedical => $"+{Value} medical supplies",
			ItemEffectType.AddCampingSupply => $"+{Value} camping supplies",
			ItemEffectType.AddGold => $"+{Value} gold",
			ItemEffectType.AddExperience => $"+{Value} XP",
			ItemEffectType.RevealMap => "Reveals nearby map",
			ItemEffectType.ReturnToVillage => "Returns to village",
			_ => Type.ToString()
		};
	}
}